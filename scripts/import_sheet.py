#!/usr/bin/env python3
"""Converts the 'export' tab of the "Plant Watering" Google Sheet into:
  - supabase/seed.sql      → to paste into the Supabase SQL Editor (after schema.sql)
  - dev/demo-data.json     → data for local demo mode (index.html?demo)

Sheet format: one row per plant (column A = name), one column per day
(row 1 = dates). Cells: AQ = water, CM = fertilizer (+ water), empty = nothing.

Usage:
  pip install openpyxl
  python3 scripts/import_sheet.py "Plant Watering.xlsx"

IDs are deterministic (uuid5): re-running it produces the same IDs.
"""
import argparse
import datetime as dt
import json
import sys
import uuid
from pathlib import Path

import openpyxl

NS = uuid.UUID("6f1c2a52-6a8e-4a43-9b1e-2f4d7c0e9a11")

ICONE = {
    "Sterlizia": "sterlizia",
    "Monstera": "monstera",
    "Monstera Monkey": "monstera-monkey",
    "Ficus Elastica": "ficus-elastica",
    "Calathea": "calathea",
    "Tradescantia purpurea (camera)": "tradescantia",
    "Tradescantia purpurea (salotto)": "tradescantia",
    "Spatafillo": "spatafillo",
    "Calla": "calla",
    "Pilea": "pilea",
    "Potho": "potho",
    "Stella di Natale": "stella-di-natale",
    "Pachira": "pachira",
    "Cactussino": "cactus",
    "Giglio Leopardo": "giglio-leopardo",
}

CODICI = {"AQ": ["acqua"], "CM": ["acqua", "concime"]}


def leggi(path: Path, tab: str):
    wb = openpyxl.load_workbook(path, data_only=True, read_only=True)
    if tab not in wb.sheetnames:
        sys.exit(f"Tab '{tab}' not found. Available tabs: {wb.sheetnames}")
    rows = list(wb[tab].iter_rows(values_only=True))
    header = rows[0]

    piante, eventi, avvisi = [], [], []
    for r in rows[1:]:
        nome = (r[0] or "").strip() if isinstance(r[0], str) else r[0]
        if not nome:
            continue
        pid = str(uuid.uuid5(NS, f"pianta:{nome}"))
        icona = ICONE.get(nome)
        if icona is None:
            avvisi.append(f"No icon for '{nome}': the app will use a generic one")
        piante.append({"id": pid, "nome": nome, "icona": icona or "generica", "archiviata": False})

        for i, v in enumerate(r[1:], start=1):
            if v is None or str(v).strip() == "":
                continue
            cod = str(v).strip().upper()
            if cod not in CODICI:
                avvisi.append(f"'{nome}', column {i + 1}: unknown value {v!r}, skipped")
                continue
            d = header[i]
            if isinstance(d, dt.datetime):
                d = d.date()
            if not isinstance(d, dt.date):
                avvisi.append(f"'{nome}', column {i + 1}: header is not a date ({d!r}), skipped")
                continue
            eventi.append({
                "id": str(uuid.uuid5(NS, f"evento:{nome}:{d.isoformat()}")),
                "pianta_id": pid,
                "data": d.isoformat(),
                "nota": None,
                "autore": "import",
                "azioni": CODICI[cod],
            })
    return piante, eventi, avvisi


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def scrivi_sql(piante, eventi, out: Path):
    righe = [
        "-- Generated by scripts/import_sheet.py — history import from the Google Sheet.",
        "-- Run AFTER schema.sql, in the Supabase SQL Editor.",
        "begin;",
        "",
        "insert into piante.piante (id, nome, icona) values",
        ",\n".join(f"  ({q(p['id'])}, {q(p['nome'])}, {q(p['icona'])})" for p in piante) + ";",
        "",
    ]
    for start in range(0, len(eventi), 500):
        blocco = eventi[start:start + 500]
        righe += [
            "insert into piante.eventi (id, pianta_id, data, autore, creato_da, creato_il) values",
            ",\n".join(
                f"  ({q(e['id'])}, {q(e['pianta_id'])}, {q(e['data'])}, 'import', null, {q(e['data'] + ' 12:00+00')})"
                for e in blocco
            ) + ";",
            "",
        ]
    azioni = [(e["id"], a) for e in eventi for a in e["azioni"]]
    for start in range(0, len(azioni), 1000):
        blocco = azioni[start:start + 1000]
        righe += [
            "insert into piante.evento_azioni (evento_id, azione) values",
            ",\n".join(f"  ({q(eid)}, {q(a)})" for eid, a in blocco) + ";",
            "",
        ]
    righe.append("commit;")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(righe) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("xlsx", type=Path, help="Google Sheet exported as .xlsx")
    ap.add_argument("--tab", default="export")
    ap.add_argument("--sql", type=Path, default=Path("supabase/seed.sql"))
    ap.add_argument("--demo", type=Path, default=Path("dev/demo-data.json"))
    args = ap.parse_args()

    piante, eventi, avvisi = leggi(args.xlsx, args.tab)
    scrivi_sql(piante, eventi, args.sql)
    args.demo.parent.mkdir(parents=True, exist_ok=True)
    args.demo.write_text(json.dumps({"piante": piante, "eventi": eventi}, ensure_ascii=False), encoding="utf-8")

    n_cm = sum(1 for e in eventi if "concime" in e["azioni"])
    date = sorted(e["data"] for e in eventi)
    print(f"{len(piante)} plants, {len(eventi)} events ({n_cm} with fertilizer)", end="")
    print(f", from {date[0]} to {date[-1]}" if date else "")
    print(f"→ {args.sql}\n→ {args.demo}")
    for a in avvisi:
        print("WARNING:", a)


if __name__ == "__main__":
    main()
